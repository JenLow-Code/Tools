// Generates migrations/0002_seed.sql from src/seed.json.
// Run:  node scripts/build-seed-sql.mjs
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const seed = JSON.parse(fs.readFileSync(path.join(root, "src/seed.json"), "utf8"));

const q = (v) => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  return "'" + String(v).replace(/'/g, "''") + "'";
};
const j = (v) => q(JSON.stringify(v ?? null));
const row = (table, cols, vals) =>
  `INSERT OR REPLACE INTO ${table} (${cols.join(", ")}) VALUES (${vals.join(", ")});`;

const out = [];
out.push("-- Auto-generated by scripts/build-seed-sql.mjs — do not edit by hand.");
out.push("-- Seeds the shared catalogue, editorial content, tools and sample marketplace.");
out.push("BEGIN TRANSACTION;");

out.push(row("metadata", ["key", "value"], [q("catalogue_checked_at"), q(seed.checkedAt)]));
out.push(row("metadata", ["key", "value"], [q("seed_version"), q(new Date().toISOString().slice(0, 10))]));

seed.categories.forEach((c, i) =>
  out.push(row("categories", ["id", "name", "subs", "fields", "icon", "position"],
    [q(c.id), q(c.name), j(c.subs), j(c.fields), q(c.icon), i])));

seed.products.forEach((p) =>
  out.push(row("products",
    ["id", "brand", "model", "category", "sub", "description", "usage", "strengths", "limitations", "specs", "manufacturer_url", "sources", "image", "image_credit", "checked_at", "editorial_refs"],
    [q(p.id), q(p.brand), q(p.model), q(p.category), q(p.sub), q(p.description), q(p.usage), j(p.strengths), j(p.limitations), j(p.specs), q(p.manufacturerUrl), j(p.sources), q(p.image), q(p.imageCredit), q(p.checkedAt), j(p.editorialRefs)])));

(seed.guides || []).forEach((g) =>
  out.push(row("guides", ["id", "title", "intro", "sections"], [q(g.id), q(g.title), q(g.intro), j(g.sections)])));

(seed.configurations || []).forEach((c) =>
  out.push(row("configurations", ["id", "title", "intro", "items"], [q(c.id), q(c.title), q(c.intro), j(c.items)])));

seed.news.forEach((n) =>
  out.push(row("news",
    ["id", "title", "category", "date", "summary", "source", "source_name", "image", "image_credit", "image_alt", "tags", "product_ids", "section"],
    [q(n.id), q(n.title), q(n.category), q(n.date), q(n.summary), q(n.source), q(n.sourceName), q(n.image), q(n.imageCredit), q(n.imageAlt), j(n.tags), j(n.productIds), q(n.section)])));

seed.releases.forEach((r) =>
  out.push(row("releases",
    ["id", "title", "family", "date", "summary", "source", "source_name", "image", "product_ids"],
    [q(r.id), q(r.title), q(r.family), q(r.date), q(r.summary), q(r.source), q(r.sourceName), q(r.image), j(r.productIds)])));

seed.events.forEach((e) =>
  out.push(row("events",
    ["id", "title", "kind", "start", "end", "region", "format", "location", "venue", "summary", "practical", "source", "source_name", "image"],
    [q(e.id), q(e.title), q(e.kind), q(e.start), q(e.end), q(e.region), q(e.format), q(e.location), q(e.venue), q(e.summary), j(e.practical), q(e.source), q(e.sourceName), q(e.image)])));

seed.tools.forEach((t, i) =>
  out.push(row("tools", ["id", "name", "status", "text", "steps", "note", "icon", "position"],
    [q(t.id), q(t.name), q(t.status), q(t.text), j(t.steps), q(t.note), q(t.icon), i])));

seed.market.forEach((m) =>
  out.push(row("listings",
    ["id", "direction", "title", "category", "product_id", "type", "price", "location", "availability", "note", "source", "is_sample"],
    [q(m.id), q(m.direction), q(m.title), q(m.category), q(m.productId), q(m.type), q(m.price), q(m.location), q(m.availability), q(m.note), q(m.source), m.isSample ? 1 : 0])));

out.push("COMMIT;");
out.push("");
fs.writeFileSync(path.join(root, "migrations/0002_seed.sql"), out.join("\n"));
console.log("Wrote migrations/0002_seed.sql —", out.length - 4, "rows");
